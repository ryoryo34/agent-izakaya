async function openSettings(page: import("@playwright/test").Page) {
  if (!(await page.locator("#settings").evaluate(e => (e as HTMLDetailsElement).open)))
    await page.locator("#settings summary").click();
}
import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('real loopback HTTP stub: explicit send, selected scope, evidence, receipt, provenance and no client key', async ({ page }) => {
  const sent: string[] = [];
  const scripts: Promise<string>[] = [];
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (/\.(ts|js)(\?|$)/.test(r.url())) scripts.push(r.text()); });
  page.on('request', r => { if (r.url().endsWith('/api/generate')) sent.push(r.postData()!); });
  await page.goto('/');
  await expect(page.locator('#destination')).toContainText('fictional-stub');
  await openSettings(page);
  await page.locator('#generation-mode').selectOption('llm');
  await openSettings(page);
  await page.locator('input[value="tsubame"]').uncheck();
  expect(sent).toHaveLength(0);
  await page.locator('#start-session').click();
  await expect(page.locator('#generation-status')).toHaveText('生成完了');
  await page.locator('#show-all').click();
  await expect(page.locator('#mode-note')).toContainText('3リクエスト');
  await expect(page.locator('#mode-note')).toContainText('90 tokens');
  expect(sent).toHaveLength(1);
  expect(sent[0]).not.toContain('tsubame');
  expect(sent[0]).not.toContain('k-before');
  await page.locator('[data-evidence]').first().click();
  await expect(page.getByRole('dialog')).toContainText('根拠ID');
  await page.keyboard.press('Escape');
  const download = page.waitForEvent('download');
  await page.locator('#download').click();
  const md = await readFile((await (await download).path())!, 'utf8');
  expect(md).toContain('LLM生成'); expect(md).toContain('fictional'); expect(md).toContain('真実性');
  expect(md).not.toContain('fictional-test-key-never-in-client');
  expect(await page.content()).not.toContain('fictional-test-key-never-in-client');
  for (const script of await Promise.all(scripts)) expect(script).not.toContain('fictional-test-key-never-in-client');
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'test-results/llm-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/llm-mobile.png', fullPage: true });
});
test('failure and cancellation preserve a completed result; later generation replaces it', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('#destination')).toContainText('fictional-stub');
  await page.locator('#start-session').click();
  await page.locator('#show-all').click();
  const oldMessages = await page.locator('#messages').innerHTML();
  const oldReceipt = await page.locator('#receipt-body').innerHTML();
  await openSettings(page);
  await page.locator('#generation-mode').selectOption('llm');
  await page.route('**/api/generate', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'テスト用のAPIエラー' }) }));
  await page.locator('#start-session').click();
  await expect(page.locator('#generation-status')).toContainText('生成失敗');
  expect(await page.locator('#messages').innerHTML()).toBe(oldMessages);
  expect(await page.locator('#receipt-body').innerHTML()).toBe(oldReceipt);
  await expect(page.locator('#download')).toBeEnabled();
  await page.unroute('**/api/generate');
  let release!: () => void;
  const blocked = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/generate', async route => { await blocked; await route.abort().catch(() => {}); });
  await page.locator('#start-session').click();
  await expect(page.locator('#generation-status')).toHaveText('生成中…');
  await expect(page.locator('#generation-mode')).toBeDisabled();
  await page.locator('#cancel-generation').click();
  await expect(page.locator('#generation-status')).toContainText('キャンセル');
  release();
  expect(await page.locator('#messages').innerHTML()).toBe(oldMessages);
  expect(await page.locator('#receipt-body').innerHTML()).toBe(oldReceipt);
  await page.unroute('**/api/generate');
  await page.locator('#start-session').click();
  await expect(page.locator('#generation-status')).toHaveText('生成完了');
  await expect(page.locator('#mode-note')).toContainText('LLM生成');
});
test('four selected projects are blocked before transmission; demo remains available', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('#destination')).toContainText('fictional-stub');
  let calls = 0;
  page.on('request', r => { if (r.url().endsWith('/api/generate')) calls++; });
  await openSettings(page);
  await page.locator('#import-toggle').click();
  const events = ['a', 'b', 'c', 'd'].map(projectId => ({ projectId, eventId: projectId, sessionId: 's', timestamp: '2026-10-06T00:00:00+09:00', kind: 'achievement', text: '架空の記録' }));
  await page.locator('#json-input').fill(JSON.stringify({ schemaVersion: 1, events }));
  await page.locator('#load-json').click();
  await openSettings(page);
  await page.locator('#generation-mode').selectOption('llm');
  await expect(page.locator('#error')).toContainText('最大3プロジェクト');
  await expect(page.locator('#start-session')).toBeDisabled();
  expect(calls).toBe(0);
  await openSettings(page);
  await page.locator('#generation-mode').selectOption('demo');
  await page.locator('#start-session').click();
  await page.locator('#show-all').click();
  await expect(page.locator('#download')).toBeEnabled();
  expect(calls).toBe(0);
});
